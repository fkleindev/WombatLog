"""Generates FlightData_<Flavor>.lua: how long every flight path hop takes, from the game's own data.

Reads the taxi tables of a WoW build from wago.tools (CSV export): every hop between two
flight masters (TaxiPath) and the points the flight follows (TaxiPathNode). The time of a
hop is the length of that route divided by the speed of a flight path taxi (433 % of
running speed, about 30.3 yards a second), plus the waits the route has built in. These are
starting values: the flight path timer measures every flight and learns the real times.

Run from the repository root:
    py tools/gen_flightdata.py --all                  every supported client
    py tools/gen_flightdata.py --all --latest         same, with the newest build of each client
    py tools/gen_flightdata.py --flavor tbc [--build 2.5.6.70577]
Needs only the Python standard library and internet access.
"""
import argparse
import csv
import math
import os
from collections import defaultdict

from gen_spelldata import FLAVORS, ROOT, latest_builds, load

TABLES = ["TaxiNodes", "TaxiPath", "TaxiPathNode"]
TAXI_SPEED = 7 * 4.33     # yards a second
TELEPORT = 0x1            # TaxiPathNode.Flags: the next point is reached by a jump, not flown


def hop_times(t):
    points = defaultdict(list)
    for r in t["TaxiPathNode"]:
        points[r["PathID"]].append((int(r["NodeIndex"]), r))
    times = {}
    for path in t["TaxiPath"]:
        pts = [r for _, r in sorted(points.get(path["ID"], []), key=lambda p: p[0])]
        if len(pts) < 2:
            continue
        length, wait = 0.0, 0.0
        for a, b in zip(pts, pts[1:]):
            wait += int(a["Delay"])
            if a["ContinentID"] != b["ContinentID"] or int(a["Flags"]) & TELEPORT:
                continue
            length += math.dist(*[[float(p[f"Loc_{i}"]) for i in range(3)] for p in (a, b)])
        if wait > 0:
            continue  # boats, zeppelins and other transports wait at their docks: not a flight
        seconds = round(length / TAXI_SPEED)
        if seconds > 0:
            times[(int(path["FromTaxiNode"]), int(path["ToTaxiNode"]))] = seconds
    return times


def generate(flavor, build, cache, out):
    t = {name: load(name, build, cache) for name in TABLES}
    names = {int(r["ID"]): r["Name_lang"] for r in t["TaxiNodes"]}
    times = hop_times(t)
    by_from = defaultdict(dict)
    for (a, b), s in times.items():
        by_from[a][b] = s
    lines = []
    for a in sorted(by_from):
        hops = ", ".join(f"[{b}] = {s}" for b, s in sorted(by_from[a].items()))
        name = names.get(a, "").replace("\n", " ")
        lines.append(f"    [{a}] = {{ {hops} }}, -- {name}")
    header = [
        f"-- Generated by tools/gen_flightdata.py from the {flavor} build {build}. Do not edit by hand.",
        "-- [fromNodeID] = { [toNodeID] = seconds }: one hop between two flight masters, worked out from",
        "-- the route's length. The flight path timer learns the real times as you fly.",
        "local ADDON, ns = ...",
        f'if ns.FLAVOR ~= "{flavor}" then return end',
        "",
        "ns.FLIGHT_DATA = {",
    ]
    text = "\n".join(header + lines + ["}", ""])
    open(out, "w", encoding="utf-8", newline="\n").write(text)
    print(f"{flavor}: {len(times)} hops from {len(by_from)} flight masters -> {out} ({len(text) // 1024} KB)")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--flavor", choices=sorted(FLAVORS), default="forever")
    ap.add_argument("--all", action="store_true", help="every flavor with its default build")
    ap.add_argument("--build", help="overrides the flavor's default build")
    ap.add_argument("--latest", action="store_true", help="use the newest build listed on wago.tools")
    ap.add_argument("--cache", help="folder to keep downloaded CSVs in")
    args = ap.parse_args()
    latest = latest_builds() if args.latest else {}
    for flavor in (sorted(FLAVORS) if args.all else [args.flavor]):
        suffix, default_build, product = FLAVORS[flavor]
        build = (not args.all and args.build) or latest.get(product) or default_build
        if build != default_build:
            print(f"{flavor}: build {build} (default in this script: {default_build})")
        generate(flavor, build, args.cache, os.path.join(ROOT, f"FlightData_{suffix}.lua"))


if __name__ == "__main__":
    main()
